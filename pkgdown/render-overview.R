# Homepage hero: three analysis views of the alcohol gallery DAG, drawn on one
# layout and one canvas so the page can crossfade between them while every
# variable stays put. The page draws the legend and captions; in the figures
# they would change height between views. Highlighting open backdoor paths
# needs dagitty; wider highlights make arrowheads overlap at the outcome.
source("tests/testthat/helper-gallery.R")
alcohol <- .metro_gallery_examples[[1L]]
stopifnot(identical(alcohol$id, "01_alcohol_heart"))
unadjusted <- metro_dag(alcohol$edges, labels = alcohol$labels,
  exposure = alcohol$exposure, outcome = alcohol$outcome,
  unadjusted = TRUE, legend = FALSE)
fixed <- attr(unadjusted, "metrodag_layout")
views <- list(
  unadjusted = unadjusted,
  adjusted = metro_dag(fixed, adjusted = c("I", "H", "D"), legend = FALSE),
  unobserved = metro_dag(fixed, adjusted = c("I", "D"), unobserved = "H",
    legend = FALSE)
)
views <- lapply(views, function(v)
  highlight_paths(v, paths = "biasing", width = 0.6) + ggplot2::labs(subtitle = NULL))
open_paths <- vapply(views, function(v) sum(attr(v, "metrodag_paths")$highlighted), integer(1))
# The homepage captions describe these counts.
stopifnot(identical(unname(open_paths), c(3L, 0L, 1L)))

dir.create("pkgdown/assets/views", recursive = TRUE, showWarnings = FALSE)
frame <- function(name) file.path("pkgdown/assets/views", paste0("alcohol-", name, ".svg"))
# Let the first view choose its height, then give every view that canvas.
save_metro_dag(frame("unadjusted"), views$unadjusted, width = 160)
box <- regmatches(readLines(frame("unadjusted"), n = 2L),
  regexpr("viewBox='[^']+'", readLines(frame("unadjusted"), n = 2L)))
height_mm <- ceiling(as.numeric(strsplit(sub("viewBox='([^']+)'", "\\1", box), " ")[[1L]][4L]) * 25.4 / 72)
for (name in names(views))
  save_metro_dag(frame(name), views[[name]], width = 160, height = height_mm)
