# Run from the repository root after installing the current package.
# This is the labelled graph from the getting-started vignette.
library(metrodag)
edges <- data.frame(
  from = c("C", "C", "X", "X", "M"),
  to = c("X", "Y", "M", "Y", "Y")
)
p <- metro_dag(edges,
  labels = c(C = "Socioeconomic background", X = "Cigarettes per day",
    M = "Tar deposits", Y = "Lung cancer"),
  exposure = "X", outcome = "Y")
dir.create("man/figures", recursive = TRUE, showWarnings = FALSE)
save_metro_dag("documentation-example.svg", p, path = "man/figures", width = 180)

# Homepage hero and gallery: copy the six annotated benchmark DAGs
# (regenerated by inst/benchmarks/run_benchmarks.R) into the site assets.
gallery <- list.files("inst/benchmarks/figures",
  pattern = "^annotated_0[1-6]_[a-z_]+\.svg$", full.names = TRUE)
gallery <- gallery[!grepl("rank_only", gallery)]
dir.create("pkgdown/assets/gallery", recursive = TRUE, showWarnings = FALSE)
file.copy(gallery, "pkgdown/assets/gallery", overwrite = TRUE)
